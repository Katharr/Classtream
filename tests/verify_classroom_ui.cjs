    await host.locator('#admin-password').fill('fixture-password');
    await host.locator('#admin-submit-btn').click();
    await host.locator('#admin-modal').waitFor({state:'hidden'});
    const auth=await host.evaluate(()=>localStorage.getItem('pystream_admin_token'));
    const headers={'x-admin-token':auth};
    await hostContext.request.post(base+'/api/screen/private',{headers,data:{enabled:false}});
    await hostContext.request.post(base+'/api/admin/display-name',{headers,data:{display_name:'陈老师'}});
