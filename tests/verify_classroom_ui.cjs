/* Real browser checks against the isolated synthetic classroom, never real data. */
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(process.env.CLASSTREAM_PLAYWRIGHT || 'playwright');

(async () => {
  const browser = await chromium.launch({ channel:'msedge', headless:true });
  const base=(process.env.CLASSTREAM_TEST_URL || 'http://127.0.0.1:18765');
  const output=path.resolve(__dirname,'../.artifacts/browser/classroom-ui');
  fs.mkdirSync(output,{recursive:true});
  const errors=[];
  const attach = page => page.on('pageerror',e=>errors.push(e.message));
  const openZoom = async page => {
    if (!await page.locator('#btn-zoom-in').isVisible()) await page.locator('#classroom-zoom-btn').click();
  };
  const stageBounds = page => page.locator('#screen-area').boundingBox();
  const sameStage = (before, after) => {
    for (const key of ['x','y','width','height']) assert.ok(Math.abs(before[key]-after[key])<1,key+' changes when a drawer opens');
  };
  const fitsViewport = async page => {
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    const width=page.viewportSize().width;
    for (const selector of ['#btn-fullscreen','#classroom-zoom-btn','#btn-screenshot','#chat-toggle-btn']) {
      const box=await page.locator(selector).boundingBox();
      assert.ok(box && box.x>=0 && box.x+box.width<=width,selector+' is outside the viewport');
    }
  };
  try {
    const hostContext = await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
    const host=await hostContext.newPage();attach(host);
    await host.goto(base+'/?host=fixture');
    assert.equal(await host.locator('html').getAttribute('lang'),'zh-CN');
    await host.locator('#admin-password').fill('incorrect');
    await host.locator('#admin-submit-btn').click();
    await host.waitForFunction(()=>document.getElementById('admin-login-error').textContent.includes('账号或密码不正确'));
    await host.locator('#admin-password').fill('fixture-password');
    await host.locator('#admin-submit-btn').click();
    await host.locator('#admin-modal').waitFor({state:'hidden'});
    const auth=await host.evaluate(()=>localStorage.getItem('pystream_admin_token'));
    const headers={'x-admin-token':auth};
    await hostContext.request.post(base+'/api/screen/private',{headers,data:{enabled:false}});
    await hostContext.request.post(base+'/api/admin/display-name',{headers,data:{display_name:'陈老师'}});
    await hostContext.request.post(base+'/api/session/new',{headers,data:{name:'信息技术 · 认识算法'}});
    await host.reload();
    await host.waitForFunction(()=>document.getElementById('screen-img').width===640);
    assert.equal(await host.locator('#sidebar').evaluate(el=>el.classList.contains('collapsed')),true);
    assert.equal(await host.locator('#chat-panel').isVisible(),false);
    assert.equal(await host.locator('#host-panel').isVisible(),false);
    const fullStage=await stageBounds(host);
    assert.ok(fullStage.width>1300,'desktop teaching area should use the available width');
    await host.locator('#classroom-settings-btn').click();
    assert.equal(await host.locator('#sidebar').getAttribute('data-panel'),'settings');
    assert.equal(await host.locator('#q-slider').isVisible(),true);
    assert.equal(await host.locator('#admin-display-name-input').isVisible(),true);
    sameStage(fullStage,await stageBounds(host));
    await host.locator('#classroom-settings-btn').click();
    await host.locator('#viewer-badge').click();
    assert.equal(await host.locator('#sidebar').getAttribute('data-panel'),'members');
    assert.equal(await host.locator('#viewer-list-panel').isVisible(),true);
    assert.equal(await host.locator('#classroom-member-manage').isVisible(),true);
    sameStage(fullStage,await stageBounds(host));
    await host.keyboard.press('Escape');
    await host.locator('#chat-toggle-btn').click();
    assert.equal(await host.locator('#chat-panel').isVisible(),true);
    sameStage(fullStage,await stageBounds(host));
    await host.locator('#classroom-chat-close').click();
    const before=await hostContext.request.get(base+'/api/status').then(r=>r.json());
    await host.locator('#classroom-menu-btn').click();
    await host.locator('#classroom-new-btn').click();
    await host.locator('#teacher-new-dialog').getByText('取消',{exact:true}).click();
    assert.equal(await host.evaluate(()=>document.activeElement.id),'classroom-menu-btn');
    const after=await hostContext.request.get(base+'/api/status').then(r=>r.json());
    assert.equal(before.session_token,after.session_token);

    const studentContext=await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
    await studentContext.addInitScript(()=>localStorage.setItem('pystream_name','旧的自定义姓名'));
    const student=await studentContext.newPage();attach(student);
    let settingsWrites=0;
    student.on('request',r=>{if(r.url().endsWith('/api/settings') && r.method()==='POST')settingsWrites++;});
    await student.goto(base+'/class');
    await student.waitForFunction(()=>document.getElementById('identity-btn').textContent.startsWith('小'));
    const nickname=await student.locator('#identity-btn').innerText();
    assert.equal(await student.locator('#name-modal,#name-input').count(),0);
    assert.equal(await student.locator('#identity-btn').isDisabled(),true);
    assert.notEqual(nickname,'旧的自定义姓名');
    await student.screenshot({path:path.join(output,'01-学生加入课堂.png')});
    await student.reload();
    await student.waitForFunction(name=>document.getElementById('identity-btn').textContent===name,nickname);
    await student.waitForFunction(()=>document.getElementById('screen-img').width===640);
    assert.equal(await student.locator('#sidebar').evaluate(el=>el.classList.contains('collapsed')),true);
    assert.equal(await student.locator('#chat-panel').isVisible(),false);
    assert.equal(await student.locator('#teacher-hide-btn').count(),0);
    await student.locator('#classroom-menu-btn').click();
    assert.equal(await student.locator('#classroom-new-btn').isVisible(),false);
    await student.keyboard.press('Escape');
    await student.locator('#viewer-badge').click();
    assert.equal(await student.locator('#classroom-member-manage').isVisible(),false);
    await student.keyboard.press('Escape');
    await student.locator('#classroom-settings-btn').click();
    assert.equal(await student.locator('#q-slider').isVisible(),false);
    assert.equal(await student.locator('#cursor-cb').isVisible(),false);
    assert.equal(await student.locator('#host-panel').isVisible(),false);
    assert.equal(await student.locator('#voice-section').isVisible(),false);
    await student.locator('#classroom-settings-btn').click();
    await student.locator('#btn-pause').click();
    await student.waitForFunction(()=>document.getElementById('stage-status').textContent.includes('已暂停'));
    assert.equal(await student.locator('#pause-label').innerText(),'继续观看');
    await student.locator('#btn-pause').click();
    assert.equal(await student.locator('#pause-label').innerText(),'暂停画面');
    await openZoom(student);
    await student.locator('#btn-zoom-in').click();
    assert.ok((await student.locator('#screen-img').getAttribute('style')).includes('1.25'));
    await openZoom(student);
    await student.locator('#btn-zoom-reset').click();
    await student.keyboard.press('Escape');
    await student.locator('#chat-toggle-btn').click();
    assert.equal(await student.locator('#chat-panel').isVisible(),true);
    await student.locator('#chat-input').fill('老师，可以再讲一遍算法的三个步骤吗？');
    await student.locator('#chat-input').press('Enter');
    await student.locator('.msg-content').filter({hasText:'算法的三个步骤'}).waitFor();
    await host.locator('#chat-toggle-btn').click();
    assert.equal(await host.locator('#chat-panel').isVisible(),true);
    await host.locator('#chat-input').fill('当然可以：先输入，再处理，最后输出。大家可以对照屏幕上的例子。');
    await host.locator('#chat-input').press('Enter');
    await student.locator('.msg-content').filter({hasText:'先输入，再处理'}).waitFor();
    const uploadError=new Promise(resolve=>student.once('dialog',async d=>{
      assert.ok(d.message().includes('暂不支持此文件格式'));await d.accept();resolve();
    }));
    await student.locator('#chat-file-input').setInputFiles({name:'lesson.exe',mimeType:'application/octet-stream',buffer:Buffer.from('test')});
    await uploadError;
    assert.equal(await student.locator('.msg-sender').filter({hasText:nickname}).count()>0,true);
    const downloadPromise=student.waitForEvent('download');
    await student.locator('#btn-screenshot').click();
    assert.ok((await downloadPromise).suggestedFilename().endsWith('.png'));
    assert.equal(settingsWrites,0);

    // Demonstration lecture content is drawn only into these test browser canvases.
    // The transport remains verified separately against the original synthetic pixels.
    await hostContext.request.post(base+'/test/mode/0');
    await host.waitForTimeout(350);
    const demo=async page=>page.locator('#screen-img').evaluate(c=>{
      const x=c.getContext('2d');x.fillStyle='#fff';x.fillRect(0,0,640,384);
      x.fillStyle='#2164df';x.fillRect(0,0,8,384);
      x.font='12px Microsoft YaHei';x.fillText('信息技术 / 第三课                                      示例教学画面',40,40);
      x.fillStyle='#18263b';x.font='bold 30px Microsoft YaHei';x.fillText('算法，让问题有解',40,94);
      x.fillStyle='#64748b';x.font='14px Microsoft YaHei';x.fillText('把复杂的问题，拆成清楚的步骤。',40,126);
      ['01  输入','02  处理','03  输出'].forEach((t,i)=>{
        x.fillStyle='#eef4ff';x.fillRect(40+i*196,170,172,76);
        x.fillStyle='#2364df';x.font='bold 19px Microsoft YaHei';x.fillText(t,58+i*196,215);
      });
      x.fillStyle='#45556d';x.font='14px Microsoft YaHei';x.fillText('想一想：怎样一步步找到三个数字中最大的一个？',40,291);
      x.fillStyle='#8a95a6';x.font='11px Microsoft YaHei';x.fillText('跟随老师一起思考 · 有问题在课堂讨论中提出',40,345);
    });
    await demo(student);await demo(host);
    await student.screenshot({path:path.join(output,'02-学生观看与讨论.png')});
    await host.locator('#chat-toggle-btn').click();
    await host.screenshot({path:path.join(output,'03-教师工作台.png')});
    await student.setViewportSize({width:320,height:640});
    await student.locator('#chat-toggle-btn').click();
    await fitsViewport(student);
    await student.screenshot({path:path.join(output,'04-手机观看.png')});
    await student.locator('#chat-toggle-btn').click();
    await student.locator('#chat-input').fill('手机端也能正常提问');
    await student.locator('#chat-input').press('Enter');
    await student.locator('.msg-content').filter({hasText:'手机端也能正常提问'}).waitFor();
    await student.screenshot({path:path.join(output,'05-手机讨论.png')});
    await student.locator('#chat-toggle-btn').click();
    await student.locator('#classroom-settings-btn').click();
    const box=await student.locator('#sidebar').boundingBox();assert.ok(box.x>=0 && box.x+box.width<=320);
    await host.setViewportSize({width:320,height:640});
    await fitsViewport(host);
    await host.locator('#teacher-command-btn').click();
    await host.locator('#teacher-command-dialog').waitFor({state:'visible'});
    const commands=await host.locator('#teacher-command-dialog').boundingBox();
    assert.ok(commands.x>=0 && commands.x+commands.width<=320);
    await host.keyboard.press('Escape');
    await host.setViewportSize({width:1440,height:960});
    await host.locator('#classroom-menu-btn').click();
    await host.locator('#classroom-new-btn').click();
    await host.locator('#teacher-new-name').fill('下一节课堂');
    await host.locator('#teacher-new-confirm').click();
    await host.locator('#link-modal').waitFor({state:'visible'});
    assert.equal(await host.locator('#session-name').innerText(),'下一节课堂');
    await host.locator('#close-link-modal').click();
    await host.locator('#classroom-menu-btn').click();
    host.once('dialog',async d=>{await d.accept();});
    await host.locator('#identity-btn').click();
    await host.locator('#admin-modal').waitFor({state:'visible'});
    assert.equal(await host.evaluate(()=>localStorage.getItem('pystream_admin_token')),null);
    assert.deepEqual(errors,[]);
    console.log('PASS: focus layout defaults, overlay drawers preserve stage geometry, member/settings/menu entry points, random nickname and refresh stability, Chinese errors, role separation, classroom rotation cancel/confirm, pause/resume, zoom/reset, two-way chat, screenshot download, teacher logout, 320px controls and dialogs, no student settings writes, no JavaScript errors.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
