    await host.waitForFunction(()=>document.getElementById('screen-img').width===640);
    assert.equal(await host.locator('#host-panel').isVisible(),true);
    const before=await hostContext.request.get(base+'/api/status').then(r=>r.json());
    await host.locator('#new-session-btn').click();
    await host.locator('#teacher-new-dialog').getByText('取消',{exact:true}).click();
    const after=await hostContext.request.get(base+'/api/status').then(r=>r.json());
    assert.equal(before.session_token,after.session_token);

    const studentContext=await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
    const student=await studentContext.newPage();attach(student);
    let settingsWrites=0;
    student.on('request',r=>{if(r.url().endsWith('/api/settings') && r.method()==='POST')settingsWrites++;});
    await student.goto(base+'/class');
    await student.locator('#name-modal').waitFor({state:'visible'});
    await student.screenshot({path:path.join(output,'01-学生加入课堂.png')});
    await student.locator('#name-submit-btn').click();
    assert.equal(await student.locator('#name-modal').isVisible(),true);
    await student.locator('#name-input').fill('张小明');
    await student.locator('#name-input').press('Enter');
    await student.locator('#name-modal').waitFor({state:'hidden'});
    await student.waitForFunction(()=>document.getElementById('screen-img').width===640);
    assert.equal(await student.locator('#sidebar').getAttribute('class'),'collapsed');
    await student.locator('#sidebar-toggle-btn').click();
    assert.equal(await student.locator('#q-slider').isVisible(),false);
    assert.equal(await student.locator('#cursor-cb').isVisible(),false);
    assert.equal(await student.locator('#host-panel').isVisible(),false);
    assert.equal(await student.locator('#voice-section').isVisible(),false);
    await student.locator('#sidebar-toggle-btn').click();
    await student.locator('#btn-pause').click();
    await student.waitForFunction(()=>document.getElementById('stage-status').textContent.includes('已暂停'));
    assert.equal(await student.locator('#pause-label').innerText(),'继续观看');
