    assert.ok((await student.locator('#screen-img').getAttribute('style')).includes('1.25'));
    await student.locator('#btn-zoom-reset').click();
    await student.locator('#chat-toggle-btn').click();
    await student.locator('#chat-input').fill('老师，可以再讲一遍算法的三个步骤吗？');
    await student.locator('#chat-input').press('Enter');
    await student.locator('.msg-content').filter({hasText:'算法的三个步骤'}).waitFor();
    await host.locator('#chat-toggle-btn').click();
    await host.locator('#chat-input').fill('当然可以：先输入，再处理，最后输出。大家可以对照屏幕上的例子。');
    await host.locator('#chat-input').press('Enter');
    await student.locator('.msg-content').filter({hasText:'先输入，再处理'}).waitFor();
    const uploadError=new Promise(resolve=>student.once('dialog',async d=>{
      assert.ok(d.message().includes('暂不支持此文件格式'));await d.accept();resolve();
    }));
    await student.locator('#chat-file-input').setInputFiles({name:'lesson.exe',mimeType:'application/octet-stream',buffer:Buffer.from('test')});
    await uploadError;
    await student.locator('#identity-btn').click();
    await student.locator('#name-input').fill('张小明同学');
    await student.locator('#name-submit-btn').click();
    await student.waitForFunction(()=>document.getElementById('identity-btn').textContent.includes('张小明同学'));
