    await host.locator('#teacher-new-confirm').click();
    await host.locator('#link-modal').waitFor({state:'visible'});
    assert.equal(await host.locator('#session-name').innerText(),'下一节课堂');
    await host.locator('#close-link-modal').click();
    await host.locator('#identity-btn').click({trial:true});
    host.once('dialog',async d=>{await d.accept();});
    await host.locator('#identity-btn').click();
    await host.locator('#admin-modal').waitFor({state:'visible'});
    assert.equal(await host.evaluate(()=>localStorage.getItem('pystream_admin_token')),null);
    assert.deepEqual(errors,[]);
    console.log('PASS: Chinese login/upload errors, name entry/rename, role separation, classroom rotation cancel/confirm, pause/resume, zoom/reset, two-way chat, screenshot download, teacher logout, 390px layout, no student settings writes, no JavaScript errors.');
