    await student.screenshot({path:path.join(output,'02-学生观看与讨论.png')});
    await host.locator('#chat-toggle-btn').click();
    await host.screenshot({path:path.join(output,'03-教师工作台.png')});
    await student.setViewportSize({width:390,height:844});
    await student.locator('#chat-toggle-btn').click();
    assert.equal(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    const fullscreenBox=await student.locator('#btn-fullscreen').boundingBox();
    assert.ok(fullscreenBox.x>=0 && fullscreenBox.x+fullscreenBox.width<=390);
    await student.screenshot({path:path.join(output,'04-手机观看.png')});
    await student.locator('#chat-toggle-btn').click();
    await student.locator('#chat-input').fill('手机端也能正常提问');
    await student.locator('#chat-input').press('Enter');
    await student.locator('.msg-content').filter({hasText:'手机端也能正常提问'}).waitFor();
    await student.screenshot({path:path.join(output,'05-手机讨论.png')});
    await student.locator('#chat-toggle-btn').click();
    await student.locator('#sidebar-toggle-btn').click();
    assert.equal(await student.locator('#sidebar-toggle-btn').getAttribute('aria-expanded'),'true');
    const box=await student.locator('#sidebar').boundingBox();assert.ok(box.width<=390);
    await host.locator('#session-name-input').fill('下一节课堂');
